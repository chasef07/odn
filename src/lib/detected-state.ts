export function servedStateFromSubdivision(subdivision: string | null): string | null {
  const code = subdivision
    ?.trim()
    .toUpperCase()
    .match(/^US-?([A-Z]{2})$/)?.[1]
  const state = code ? STATE_NAMES[code] : undefined
  return state && AVAILABLE_STATES.includes(state) ? state : null
}
